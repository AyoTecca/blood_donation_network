-- 1) Request history table
CREATE TABLE transfusion_request_history (
    history_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id           NUMBER NOT NULL,
    operation_type       VARCHAR2(20) NOT NULL,
    old_status           VARCHAR2(50),
    new_status           VARCHAR2(50),
    old_units_required   NUMBER,
    new_units_required   NUMBER,
    changed_at           DATE DEFAULT SYSDATE NOT NULL,
    changed_by           VARCHAR2(255) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
    change_note          VARCHAR2(1000)
);
/

