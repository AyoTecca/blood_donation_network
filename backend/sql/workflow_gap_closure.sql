-- 7) Views for UI pages (history, open requests, notifications)
CREATE OR REPLACE VIEW vw_request_history_timeline AS
SELECT
    h.history_id,
    h.request_id,
    h.operation_type,
    h.old_status,
    h.new_status,
    h.old_units_required,
    h.new_units_required,
    h.changed_at,
    h.changed_by,
    h.change_note,
    p.first_name || ' ' || p.last_name AS patient_name,
    f.facility_name
FROM transfusion_request_history h
JOIN transfusion_requests r ON r.request_id = h.request_id
JOIN patients p ON p.patient_id = r.patient_id
JOIN facilities f ON f.facility_id = p.current_facility_id;
/

CREATE OR REPLACE VIEW vw_open_requests_by_facility AS
SELECT
    r.request_id,
    p.current_facility_id AS facility_id,
    f.facility_name,
    p.first_name || ' ' || p.last_name AS patient_name,
    bt.type_group || bt.rh_factor AS blood_type,
    r.urgency_level,
    r.units_required,
    r.status,
    r.request_date
FROM transfusion_requests r
JOIN patients p ON p.patient_id = r.patient_id
JOIN facilities f ON f.facility_id = p.current_facility_id
JOIN blood_types bt ON bt.blood_type_id = p.blood_type_id
WHERE r.status IN ('Pending', 'Partially Fulfilled');
/

CREATE OR REPLACE VIEW vw_notifications_feed AS
SELECT
    n.notification_id,
    n.request_id,
    n.facility_id,
    f.facility_name,
    n.recipient_role,
    n.event_type,
    n.message_text,
    n.is_read,
    n.created_at,
    n.created_by
FROM app_notifications n
LEFT JOIN facilities f ON f.facility_id = n.facility_id;
